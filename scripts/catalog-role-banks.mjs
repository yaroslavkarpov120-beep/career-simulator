/**
 * @param {typeof import('./build-catalog.mjs').entry extends never ? never : any[]} baseEntries - from manual PROFESSIONS
 * @param {typeof entry} entryFn
 */
export function expandProfessions(baseEntries, entryFn, targetTotal = TARGET_TOTAL) {
  const ids = new Set(baseEntries.map((p) => p.id));
  const extra = [];
  const categories = Object.keys(ROLE_BANKS);

  let round = 0;
  while (baseEntries.length + extra.length < targetTotal) {
    for (const category of categories) {
      if (baseEntries.length + extra.length >= targetTotal) break;
      const bank = ROLE_BANKS[category];
      const defaults = CATEGORY_DEFAULTS[category];
      for (let i = 0; i < bank.length; i++) {
        if (baseEntries.length + extra.length >= targetTotal) break;
        const [suffix, ru, en] = bank[i];
        const tier = round > 0 ? `-v${round + 1}` : "";
        let id = `${category}-${suffix}${tier}`;
        if (ids.has(id)) {
          id = `${category}-${suffix}-${round}-${i}${tier}`;
        }
        if (ids.has(id)) continue;
        ids.add(id);
        const ai = Math.min(
          85,
          Math.max(5, defaults.ai + ((i + round) % 7) - 3)
        );
        const min = defaults.min + ((i + round * 3) % 12) * 2500;
        const max = defaults.max + ((i + round * 5) % 15) * 3000;
        extra.push(
          entryFn(id, ru, en, category, ai, min, max, {
            featured: false,
          })
        );
      }
    }
    round++;
    if (round > 20) break;
  }

  return extra;
}

