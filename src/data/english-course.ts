export function getLevelById(id: string): Level | undefined {
  return ENGLISH_COURSE.find((l) => l.id === id);
}

export function getLessonById(levelId: string, lessonId: string): Lesson | undefined {
  return getLevelById(levelId)?.lessons.find((l) => l.id === lessonId);
}
